def create_radar_chart(skill_scores):
    categories = list(skill_scores.keys())
    values = list(skill_scores.values())

    categories_closed = categories + [categories[0]]
    values_closed = values + [values[0]]

    fig = go.Figure()

    fig.add_trace(go.Scatterpolar(
        r=values_closed,
        theta=categories_closed,
        fill="toself",
        name="評価スコア",
        line=dict(color="#1f77b4", width=3),
        fillcolor="rgba(31, 119, 180, 0.25)"
    ))

    fig.update_layout(
        polar=dict(
            radialaxis=dict(
                visible=True,
                range=[0, 5],
                tickvals=[1, 2, 3, 4, 5],
                ticktext=["1", "2", "3", "4", "5"]
            )
        ),
        showlegend=False,
        height=650,
        margin=dict(l=80, r=80, t=80, b=80),
        title="マネージャースキル レーダーチャート"
    )

    return fig


def create_summary(skill_scores):
    average_score = round(sum(skill_scores.values()) / len(skill_scores), 2)

    sorted_scores = sorted(skill_scores.items(), key=lambda x: x[1], reverse=True)
    strengths = sorted_scores[:3]
    improvements = sorted_scores[-3:]

    return average_score, strengths, improvements


