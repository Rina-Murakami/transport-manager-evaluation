def calculate_skill_scores(responses):
    skill_scores = {}

    for skill, scores in responses.items():
        if len(scores) > 0:
            skill_scores[skill] = round(sum(scores) / len(scores), 2)
        else:
            skill_scores[skill] = 0

    return skill_scores


