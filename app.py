def main():
    st.title("🚚 運送会社マネージャー評価・分析システム")

    st.markdown(
        """
        このシステムでは、運送会社のマネージャーに必要な10項目のスキルを、
        各10問・5段階評価で診断します。

        評価結果は、項目別平均点、レーダーチャート、総合分析、強み、改善課題として表示されます。
        """
    )

    with st.sidebar:
        st.header("評価対象者情報")
        manager_name = st.text_input("マネージャー名", value="")
        department = st.text_input("所属拠点・部署", value="")
        evaluator_name = st.text_input("評価者名", value="")

        st.divider()

        st.header("評価基準")
        st.write("5：非常にできている")
        st.write("4：できている")
        st.write("3：普通")
        st.write("2：あまりできていない")
        st.write("1：できていない")

    st.divider()

    responses = {}

    for skill, questions in SKILL_QUESTIONS.items():
        with st.expander(f"{skill} の評価", expanded=False):
            st.subheader(skill)

            scores = []

            for i, question in enumerate(questions, start=1):
                score = st.radio(
                    label=f"Q{i}. {question}",
                    options=[1, 2, 3, 4, 5],
                    index=2,
                    horizontal=True,
                    key=f"{skill}_{i}"
                )
                scores.append(score)

            responses[skill] = scores

    st.divider()

    if st.button("分析を実行する", type="primary"):
        skill_scores = calculate_skill_scores(responses)
        average_score, strengths, improvements = create_summary(skill_scores)

        st.header("分析結果")

        info_col1, info_col2, info_col3 = st.columns(3)

        with info_col1:
            st.metric("評価対象者", manager_name if manager_name else "未入力")

        with info_col2:
            st.metric("所属", department if department else "未入力")

        with info_col2:
            st.metric("所属", department if department else "未入力")

if __name__ == "__main__":
    main()